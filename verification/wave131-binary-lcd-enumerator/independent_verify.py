"""Independent exact verifier for Wave 131.

No discovery code is imported.  The verifier rederives the subset census
and audits the sealed rational ordinary enumerator using exact Fraction and
Krawtchouk arithmetic.
"""

from __future__ import annotations

import argparse
import ctypes
