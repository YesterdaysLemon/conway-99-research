Q = Fraction
ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
DISCOVERY = ROOT / "attempts" / "wave131-binary-lcd-enumerator"
MANIFEST_SHA256 = (
    "c305de05df2001d869db3dbfc14f7a2a8c7f305ce43471c56c66dc775e89d576"
)
N = 99
K_IMAGE = 54
K_DUAL = 45
IMAGE_SIZE = 1 << K_IMAGE
DUAL_SIZE = 1 << K_DUAL


def require(condition: bool, message: str) -> None:
    if not condition:
        raise AssertionError(message)


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def canonical(data: object) -> str:
    return json.dumps(data, indent=2, sort_keys=True) + "\n"


def free_memory_percent() -> float:
    if os.name != "nt":
        return 100.0

    class MemoryStatus(ctypes.Structure):
        _fields_ = [
            ("length", ctypes.c_ulong),
            ("load", ctypes.c_ulong),
            ("total_phys", ctypes.c_ulonglong),
            ("available_phys", ctypes.c_ulonglong),
            ("total_page", ctypes.c_ulonglong),
            ("available_page", ctypes.c_ulonglong),
            ("total_virtual", ctypes.c_ulonglong),
            ("available_virtual", ctypes.c_ulonglong),
            ("available_extended", ctypes.c_ulonglong),
        ]

    state = MemoryStatus()
    state.length = ctypes.sizeof(state)
    require(
        bool(ctypes.windll.kernel32.GlobalMemoryStatusEx(ctypes.byref(state))),
        "GlobalMemoryStatusEx failed",
    )
    return 100.0 * state.available_phys / state.total_phys


def preinspect() -> dict[str, object]:
    manifest = DISCOVERY / "package-manifest.sha256"
    require(sha256(manifest) == MANIFEST_SHA256, "manifest hash drift")
    entries = 0
    for line in manifest.read_text(encoding="utf-8").splitlines():
        expected, relative = line.split("  ", 1)
        require(sha256(ROOT / relative) == expected, f"sealed drift: {relative}")
        entries += 1
    require(entries == 13, "manifest entry count drift")
    return {
        "manifest_sha256": MANIFEST_SHA256,
        "entries_checked": entries,
    }


